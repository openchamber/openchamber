import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';

const entry = fileURLToPath(new URL('../packages/ui/src/components/chat/uiBlocks/serverValidation.ts', import.meta.url));
const output = fileURLToPath(new URL('../packages/web/server/lib/opencode/ui-block-validation.generated.js', import.meta.url));
const result = await Bun.build({ entrypoints: [entry], target: 'node', format: 'esm', minify: true, env: 'disable' });
if (!result.success || result.outputs.length !== 1) throw new Error('UI block validation build failed', { cause: result.logs });
const content = `// Generated by bun run --cwd packages/ui ui-blocks:generate. Do not edit.\n${await result.outputs[0].text()}`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('UI block validation is stale; run ui-blocks:generate');
} else {
  await writeFile(output, content);
}
