/** simple-icons' own title → slug rule, for entries without an explicit slug. */
const titleToSlug = (title) => title
  .toLowerCase()
  .replaceAll('+', 'plus')
  .replaceAll('.', 'dot')
  .replaceAll('&', 'and')
  .normalize('NFD')
  .replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]/g, '');

/** Black or white, whichever reads better on the fill (YIQ brightness). */
const glyphColorOn = (hex) => {
  const r = Number.parseInt(hex.slice(0, 2), 16);
  const g = Number.parseInt(hex.slice(2, 4), 16);
  const b = Number.parseInt(hex.slice(4, 6), 16);
  return (r * 299 + g * 587 + b * 114) / 1000 >= 150 ? '#000000' : '#FFFFFF';
};

const dataResponse = await fetch(`${SIMPLE_ICONS}/data/simple-icons.json`);
if (!dataResponse.ok) throw new Error('simple-icons data unavailable');
const data = await dataResponse.json();
const icons = Array.isArray(data) ? data : data.icons;
const hexBySlug = new Map(icons.map((icon) => [icon.slug ?? titleToSlug(icon.title), icon.hex]));

const lines = [];
for (const [id, slug] of Object.entries(BRANDS)) {
  const hex = hexBySlug.get(slug);
  const response = await fetch(`${SIMPLE_ICONS}/icons/${slug}.svg`);
  if (!response.ok || !hex) {
    console.log(`${id} (${slug}): MISS`);
    continue;
  }
  const svg = await response.text();
  const match = svg.match(/ d="([^"]+)"/);
  if (!match) throw new Error(`no path in ${slug}`);
  lines.push(`  '${id}': { path: '${match[1]}', color: '#${hex}', glyph: '${glyphColorOn(hex)}' },`);
  console.log(`${id} (${slug}): ok`);
}

