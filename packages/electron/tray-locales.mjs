export const normalizeTrayLocale = (locale) => (
  Object.hasOwn(TRAY_LOCALE_DICTIONARIES, locale) ? locale : 'en'
);

export const trayLabel = (locale, key) => (
  TRAY_LOCALE_DICTIONARIES[normalizeTrayLocale(locale)][key] ?? key
);

// Replaces {name} placeholders with the matching value; leaves unknown
// placeholders untouched so a missing value never renders as "undefined".
export const formatTrayLabel = (locale, key, values = {}) => (
  trayLabel(locale, key).replace(/\{(\w+)\}/g, (match, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : match
  ))
);
