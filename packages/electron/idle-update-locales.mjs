export const idleUpdateText = (locale, key, values = {}) => {
  const dictionary = idleUpdateDictionaries[locale] ?? idleUpdateDictionaries.en;
  const template = dictionary[key] ?? idleUpdateDictionaries.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
};

export const idleUpdateWindowHtml = ({ locale, seconds, reason }) => {
  const countKey = seconds === 1 ? 'countdownOne' : 'countdown';
  const rtl = locale === 'ar' || locale === 'he';
  const escape = (value) => String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
  const title = escape(idleUpdateText(locale, 'title'));
  const body = escape(idleUpdateText(locale, countKey, { seconds }));
  const detail = reason ? escape(idleUpdateText(locale, reason)) : '';
  const cancel = escape(idleUpdateText(locale, 'cancel'));
  return `<!doctype html>
<html lang="${escape(locale)}" dir="${rtl ? 'rtl' : 'ltr'}">
<meta charset="utf-8">
<title>${title}</title>
<style>
  body { margin: 0; font: 14px/1.4 system-ui, sans-serif; background: #1c1c1c; color: #f4f4f5; }
  main { padding: 20px 22px; display: flex; flex-direction: column; gap: 12px; }
  h1 { margin: 0; font-size: 15px; font-weight: 600; }
  p { margin: 0; color: #d4d4d8; }
  a { align-self: flex-start; color: inherit; text-decoration: none; border: 1px solid #3f3f46; border-radius: 8px; padding: 6px 12px; }
</style>
<main>
  <h1>${title}</h1>
  <p id="countdown">${body}</p>
  <p id="detail">${detail}</p>
  <a href="https://idle-update.invalid/cancel">${cancel}</a>
</main>
</html>`;
};
